import { readFileSync, writeFileSync } from "node:fs";
import solc from "solc";

const root = (p) => readFileSync(new URL(p, import.meta.url), "utf8");
const input = {
  language: "Solidity",
  sources: {
    "ShieldedPool.sol": { content: root("../contracts/ShieldedPool.sol") },
    "ShieldedVerifierMock.sol": { content: root("../contracts/ShieldedVerifierMock.sol") },
  },
  settings: {
    optimizer: { enabled: true, runs: 200 },
    outputSelection: { "*": { "*": ["abi", "evm.bytecode.object"] } },
  },
};
const output = JSON.parse(solc.compile(JSON.stringify(input)));
const errors = (output.errors ?? []).filter((e) => e.severity === "error");
if (errors.length > 0) {
  console.error(errors);
  process.exit(1);
}
const pool = output.contracts["ShieldedPool.sol"]["ShieldedPool"];
const mock = output.contracts["ShieldedVerifierMock.sol"]["ShieldedVerifierMock"];

const out = `// GENERATED by scripts/compile-shielded.mjs — do not hand-edit.
export const SHIELDED_SOLC_VERSION = "0.8.26";
export const SHIELDED_ABI = ${JSON.stringify(pool.abi)} as const;
export const SHIELDED_BYTECODE = "0x${pool.evm.bytecode.object}";
export const SHIELDED_MOCK_ABI = ${JSON.stringify(mock.abi)} as const;
export const SHIELDED_MOCK_BYTECODE = "0x${mock.evm.bytecode.object}";
`;
writeFileSync(new URL("../lib/shielded-artifact.ts", import.meta.url), out);
console.log("wrote lib/shielded-artifact.ts");
